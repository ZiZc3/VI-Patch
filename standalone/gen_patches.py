#!/usr/bin/env python3
"""Turn PPSA38500.xml (PS Patch System format) into patches.h for the loader.

Usage: gen_patches.py PPSA38500.xml originals.txt [--off "Patch name"]... > patches.h

Every <Line Type="bytes"> needs its original bytes in originals.txt. If one is
missing, the script stops and names it: start the loader once with dump=1 in
its config to log the bytes currently at every address, then add the line.

Write order inside a patch: lines that fill unused space (original bytes all
00 or all CC) go first, so a cave holds its code before anything jumps to it.
The remaining lines are written last to first.
"""
import argparse
import sys
import xml.etree.ElementTree as ET


def load_originals(path):
    orig = {}
    with open(path) as f:
        for n, raw in enumerate(f, 1):
            line = raw.split("#", 1)[0].split()
            if not line:
                continue
            if len(line) != 3:
                sys.exit(f"{path}:{n}: expected 'address length bytes'")
            addr, length = int(line[0], 16), int(line[1])
            data = bytes(length) if line[2] == "zero" else bytes.fromhex(line[2])
            if len(data) != length:
                sys.exit(f"{path}:{n}: length {length} but {len(data)} bytes given")
            orig[(addr, length)] = data
    return orig


def is_padding(data):
    return all(b == 0 for b in data) or all(b == 0xCC for b in data)


def c_bytes(data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16])
            for i in range(0, len(data), 16)]
    return "{\n    " + ",\n    ".join(rows) + "\n}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("xml")
    ap.add_argument("originals")
    ap.add_argument("--off", action="append", default=[],
                    help="patch that starts disabled in the default config")
    args = ap.parse_args()

    orig = load_originals(args.originals)
    root = ET.parse(args.xml).getroot()
    title = root.findtext("TitleID/ID", "").strip()
    out = [f"/* Generated by gen_patches.py from {args.xml.split('/')[-1]} ({title}). Do not edit. */",
           "#pragma once", "#include <stdint.h>", "",
           "struct line { uint64_t addr; uint32_t len; const uint8_t *orig; const uint8_t *new_; };",
           "struct patch { const char *name; const char *app_ver; int default_on; int n; const struct line *lines; };",
           ""]
    patches, missing, names = [], [], set()
    for pi, md in enumerate(root.iter("Metadata")):
        name = md.get("Name", f"patch {pi}")
        if name in names:
            sys.exit(f"duplicate patch name: {name}")
        names.add(name)
        lines = []
        for li, ln in enumerate(md.iter("Line")):
            if ln.get("Type") != "bytes":
                sys.exit(f"{name}: line type {ln.get('Type')!r} is not supported")
            addr = int(ln.get("Address"), 16)
            new = bytes.fromhex(ln.get("Value"))
            o = orig.get((addr, len(new)))
            if o is None:
                missing.append(f"  {name}: 0x{addr:08x} {len(new)}")
                continue
            lines.append((addr, o, new))
        if not lines:
            continue
        caves = [l for l in lines if is_padding(l[1])]
        code = [l for l in lines if not is_padding(l[1])]
        ordered = caves + code[::-1]
        for li, (addr, o, new) in enumerate(ordered):
            out.append(f"static const uint8_t p{pi}_{li}_orig[] = {c_bytes(o)};")
            out.append(f"static const uint8_t p{pi}_{li}_new[] = {c_bytes(new)};")
        out.append(f"static const struct line p{pi}_lines[] = {{")
        for li, (addr, o, new) in enumerate(ordered):
            out.append(f"    {{0x{addr:08x}, {len(new)}, p{pi}_{li}_orig, p{pi}_{li}_new}},")
        out.append("};")
        out.append("")
        patches.append((name, md.get("AppVer", ""), name not in args.off, pi, len(ordered)))
    if missing:
        sys.exit("no original bytes in " + args.originals + " for:\n" + "\n".join(missing))
    for off in args.off:
        if off not in names:
            print(f"warning: --off {off!r} is not a patch in {args.xml}", file=sys.stderr)
    out.append(f'#define GAME_TITLE_ID "{title}"')
    out.append("static const struct patch patches[] = {")
    for name, ver, on, pi, n in patches:
        out.append(f'    {{"{name}", "{ver}", {int(on)}, {n}, p{pi}_lines}},')
    out.append("};")
    out.append("#define NUM_PATCHES (sizeof(patches) / sizeof(patches[0]))")
    print("\n".join(out))


if __name__ == "__main__":
    main()
